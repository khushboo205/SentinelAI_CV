import asyncio
from fastapi import FastAPI, UploadFile, File, BackgroundTasks
from pydantic import BaseModel
from typing import Dict, Any, List

from src.ai.orchestrator import AIOrchestrator

app = FastAPI(title="SentinelAI Orchestration Engine")
orchestrator = AIOrchestrator()

# API Models mapping to the frontend's expected mock response format
class QualityResponse(BaseModel):
    blurLevel: str
    lighting: str
    noise: str
    summary: str

class EnhancementResponse(BaseModel):
    technique: str
    reason: str
    confidenceScore: float

class DetectionResponse(BaseModel):
    object: str
    confidence: float
    timestamp: str

class TrackingResponse(BaseModel):
    subject: str
    movement: str
    timestamp: str

class EvidenceResponse(BaseModel):
    incidentSummary: str
    keyFindings: List[str]
    riskHeatmapArea: str

class AnalysisResponse(BaseModel):
    qualityAgent: QualityResponse
    enhancementAgent: List[EnhancementResponse]
    detectionAgent: List[DetectionResponse]
    trackingAgent: List[TrackingResponse]
    evidenceAgent: EvidenceResponse

import cv2
import numpy as np
import base64

@app.post("/analyze")
async def analyze_media(media: UploadFile = File(...)):
    # Read frame data
    file_bytes = await media.read()
    
    # Decode directly to OpenCV format
    np_arr = np.frombuffer(file_bytes, np.uint8)
    frame_cv = cv2.imdecode(np_arr, cv2.IMREAD_COLOR)
    
    if frame_cv is None:
        return {"success": False, "error": "Invalid image file format"}
    
    # Run the orchestrator pipeline
    context = await orchestrator.process_media(frame_cv)
    
    # Map the PipelineContext back to the format the frontend expects
    response = {
        "qualityAgent": {
            "blurLevel": context.scene_metadata.blur_level,
            "lighting": context.scene_metadata.lighting,
            "noise": context.scene_metadata.noise,
            "summary": context.scene_metadata.summary
        },
        "enhancementAgent": [
            {
                "technique": context.enhancement_model_selected or "Skip enhancement",
                "reason": f"Selected due to {context.scene_metadata.lighting} lighting and {context.scene_metadata.blur_level} blur",
                "confidenceScore": 0.95
            }
        ],
        "detectionAgent": [
            {
                "object": det.object_class,
                "confidence": det.confidence,
                "timestamp": det.timestamp
            } for det in context.detections
        ],
        "trackingAgent": [
            {
                "subject": trk.subject_id,
                "movement": trk.movement,
                "timestamp": trk.timestamp
            } for trk in context.tracking
        ],
        "evidenceAgent": {
            "incidentSummary": context.evidence.get("incidentSummary", ""),
            "keyFindings": context.evidence.get("keyFindings", []),
            "riskHeatmapArea": context.evidence.get("riskHeatmapArea", "")
        }
    }
    
    return {"success": True, "analysis": response}

